// Writes the panel page (editor/panel.html) into src/panelHtml.ts as a string.
//
// Drawdy builds submissions with esbuild only (no plugins), so an HTML file
// cannot be imported; we generate a plain TS module and commit it.
// Run `npm run gen:editor` after editing editor/panel.html.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// a checkout with CRLF endings (Windows, autocrlf) must give the same file as one with LF
const html = readFileSync(join(root, "editor/panel.html"), "utf8").replace(/\r\n/g, "\n");
writeFileSync(
    join(root, "src/panelHtml.ts"),
    "// GENERATED by scripts/gen-editor.mjs from editor/panel.html.\n" +
        "// Do not edit by hand; edit the HTML and run `npm run gen:editor`.\n\n" +
        "export const PANEL_HTML: string = " +
        JSON.stringify(html) +
        ";\n"
);
console.log(`src/panelHtml.ts written (${html.length} chars of HTML)`);

// The toolbar button takes an svg only, so the logo goes in as an <image>.
// icon.png is logo.png scaled down (96px) to keep the extension small.
const png = readFileSync(join(root, "icon.png")).toString("base64");
writeFileSync(
    join(root, "src/iconData.ts"),
    "// GENERATED by scripts/gen-editor.mjs from icon.png. Do not edit by hand.\n\n" +
        `export const ICON_PNG_DATA_URI: string = "data:image/png;base64,${png}";\n`
);
console.log(`src/iconData.ts written (${png.length} chars of base64)`);
